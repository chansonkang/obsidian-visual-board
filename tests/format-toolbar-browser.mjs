import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import { richHarness, selectRendered } from './rich-editor-harness.mjs';
const h = await richHarness('# Rich\n\nFirst paragraph.\n\nSecond paragraph.\n');
const checks = [];
try {
  const bar = h.frame.getByTestId('format-toolbar');
  assert.equal(await bar.isVisible(), false);
  const geometry = await h.frame.evaluate(() => ({ view: { ...board().view }, nodes: board().nodes.map(({ id,x,y,w,h }) => ({ id,x,y,w,h })) }));
  await h.editor.getByText('First paragraph.', { exact:true }).click();
  await bar.waitFor({ state:'visible' });
  assert.equal(await bar.getAttribute('role'), 'toolbar');
  for (const label of ['正文','标题 1','标题 2','标题 3','加粗','斜体','圆点列表','编号列表','引用','完成']) assert.equal(await bar.getByRole('button', { name:label, exact:true }).count(), 1);
  checks.push('Single click reveals Chinese heading/list/inline formatting controls');
  await selectRendered(h.editor, 'First');
  await h.frame.getByTestId('format-bold').click();
  await h.frame.waitForFunction(() => document.querySelector('[data-testid="format-bold"]').getAttribute('aria-pressed')==='true');
  assert.equal(await h.editor.locator('strong,b').textContent(), 'First');
  assert.equal(await h.editor.evaluate(el => document.activeElement===el && getSelection().toString()==='First'),true);
  await h.frame.getByTestId('format-italic').click();
  await h.flush();
  assert.match(await h.body(), /\*\*\*First\*\*\*|\*\*_First_\*\*|_\*\*First\*\*_/);
  checks.push('Visible inline buttons retain selected text, editor focus and pressed state');
  await selectRendered(h.editor, 'Second', true);
  await h.frame.getByTestId('format-ordered-list').click();
  assert.equal(await h.editor.locator('ol li').textContent(),'Second paragraph.');
  await selectRendered(h.editor, 'Second paragraph.'); await h.page.keyboard.press('ArrowRight'); await h.page.keyboard.press('Enter'); await h.page.keyboard.insertText('Third paragraph.');
  assert.deepEqual(await h.editor.locator('ol li').allTextContents(),['Second paragraph.','Third paragraph.']);
  await h.flush();
  assert.match(await h.body(), /1\. +Second paragraph\.[\s\S]*2\. +Third paragraph\./);
  checks.push('Caret-only numbered-list action and Enter continue numbering');
  assert.deepEqual(await h.frame.evaluate(() => ({ view:{...board().view},nodes:board().nodes.map(({id,x,y,w,h})=>({id,x,y,w,h})) })), geometry);
  const clamp = async () => {
    const box=await bar.boundingBox(),size=h.page.viewportSize();
    assert.ok(box.x>=7&&box.y>=7&&box.x+box.width<=size.width-7&&box.y+box.height<=size.height-7,JSON.stringify({box,size}));
  };
  await clamp();
  await h.page.screenshot({path:new URL('../evidence/format-toolbar-desktop.png',import.meta.url).pathname});
  await h.page.setViewportSize({width:480,height:800});
  await h.page.waitForTimeout(100); await clamp();
  await h.frame.getByTestId('format-h3').click();
  assert.equal(await h.editor.locator('h3').count()>0,true);
  await h.frame.getByTestId('format-done').click();
  await bar.waitFor({state:'hidden'}); await h.flush();
  assert.equal(await h.editor.getAttribute('data-markdown-mode'),'read');
  checks.push('Toolbar stays in desktop/mobile viewport without changing geometry; Done saves and closes');
  assert.deepEqual(h.errors,[]);assert.deepEqual(h.requests,[]);
  await mkdir(new URL('../evidence/',import.meta.url),{recursive:true});
  await writeFile(new URL('../evidence/format-toolbar-browser.json',import.meta.url),JSON.stringify({passed:true,checks,errors:h.errors,externalRequests:h.requests},null,2)+'\n');
  console.log(JSON.stringify({passed:true,groups:checks.length,checks}));
} finally { await h.close(); }
